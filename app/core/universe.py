def universe() -> list[tuple[str, str]]:
    """스캔 대상 (ticker, market) 목록. 중복 제거."""
    seen: set[tuple[str, str]] = set()
    out: list[tuple[str, str]] = []
    for t in _SP500:
        k = (t, "US")
        if k not in seen:
            seen.add(k)
            out.append(k)
    for t in _KOSPI:
        k = (t, "KR")
        if k not in seen:
            seen.add(k)
            out.append(k)
    return out


def exclude_held(cands: list[tuple[str, str]], held: set[tuple[str, str]]) -> list[tuple[str, str]]:
    """이미 보유/관심 중인 종목 제외."""
    return [c for c in cands if c not in held]


def chunks(items: list, size: int) -> list[list]:
    """배치 다운로드용 분할."""
    return [items[i:i + size] for i in range(0, len(items), size)]
